  // --- HIGH-PERFORMANCE ZERO-RESOURCE INDEXES ---
  static final Map<String, DrugInfo> _barcodeIndex = _buildBarcodeIndex();
  static List<String>? _precomputedBlobsCache;
  static List<String> get _precomputedBlobs {
    if (_precomputedBlobsCache == null ||
        _precomputedBlobsCache!.length != allDrugs.length) {
      _precomputedBlobsCache = _buildSearchBlobs();
    }
    return _precomputedBlobsCache!;
  }
  static final Map<String, List<DrugInfo>> _searchCache = {};

  static Map<String, DrugInfo> _buildBarcodeIndex() {
    final map = <String, DrugInfo>{};
    for (final drug in allDrugs) {
      map[drug.id.toLowerCase()] = drug;
      for (final b in drug.barcodes) {
        final cleanB = b.trim().replaceAll(RegExp(r'[^0-9a-zA-Z]'), '').toLowerCase();
        if (cleanB.isNotEmpty) {
          map[cleanB] = drug;
          // Also index without leading 0 for 14-digit GTINs
          if (cleanB.startsWith('0') && cleanB.length == 14) {
            map[cleanB.substring(1)] = drug;
          }
        }
      }
    }
    return map;
  }

  static List<String> _buildSearchBlobs() {
    final list = <String>[];
    for (final d in allDrugs) {
      final raw = '${d.tradeName} ${d.genericName} ${d.company} ${d.category} ${d.uses} ${d.availableDosages.join(' ')} ${d.barcodes.join(' ')}';
      final norm = DrugInfo.normalizeArabic(raw);
      list.add('$raw $norm'.toLowerCase());
    }
    return list;
  }

  /// Fast search through database by name, active ingredient, company, category, uses, or dosage
  static List<DrugInfo> search(String query, {String? category, bool? onlyRare}) {
    final cleanQuery = query.trim();
    if (cleanQuery.isEmpty && (category == null || category == Ar.allCategories) && onlyRare != true) {
      return allDrugs;
    }

    final cacheKey = '$cleanQuery|$category|$onlyRare';
    if (_searchCache.containsKey(cacheKey)) {
      return _searchCache[cacheKey]!;
    }

    final qLower = cleanQuery.toLowerCase();
    final qNorm = DrugInfo.normalizeArabic(qLower);

    final results = <DrugInfo>[];
    for (int i = 0; i < allDrugs.length; i++) {
      final d = allDrugs[i];
      if (onlyRare == true && !d.isRare) continue;
      if (category != null && category != Ar.allCategories && d.category != category) continue;

      if (cleanQuery.isEmpty) {
        results.add(d);
        continue;
      }

      final blob = _precomputedBlobs[i];
      if (blob.contains(qLower) || blob.contains(qNorm)) {
        results.add(d);
      }
    }

    if (_searchCache.length > 200) {
      _searchCache.clear();
    }
    _searchCache[cacheKey] = List.unmodifiable(results);
    return results;
  }

  /// Get distinct categories list
  static List<String> getCategories() {
    final set = allDrugs.map((d) => d.category).toSet();
    return [Ar.allCategories, ...set];
  }

  /// Find a drug by Barcode, EAN-13, UPC, QR code, or GS1 DataMatrix (Instant O(1))
  static DrugInfo? findByBarcode(String rawBarcode) {
    var clean = rawBarcode.trim();
    if (clean.isEmpty) return null;

    // 0. Clean GS1 control characters: ASCII GS \x1d, \x1e, \x04
    clean = clean.replaceAll(RegExp(r'[\x1d\x1e\x04]'), '');
    if (clean.startsWith('[)>')) {
      clean = clean.replaceFirst(RegExp(r'^\[\)>[0-9]{2}'), '');
    }

    final cleanDigits = clean.replaceAll(RegExp(r'[^0-9a-zA-Z]'), '').toLowerCase();

    // 1. Instant O(1) Index Lookup
    if (_barcodeIndex.containsKey(cleanDigits)) {
      return _barcodeIndex[cleanDigits];
    }
    if (cleanDigits.startsWith('0') && cleanDigits.length == 14) {
      final ean13 = cleanDigits.substring(1);
      if (_barcodeIndex.containsKey(ean13)) {
        return _barcodeIndex[ean13];
      }
    }

    // 2. GS1 DataMatrix parser: extracts AI (01) 13 or 14-digit GTIN
    final gs1GtinMatch = RegExp(r'(?:\(01\)|^01)([0-9]{13,14})').firstMatch(clean);
    if (gs1GtinMatch != null) {
      final gtin = gs1GtinMatch.group(1)!;
      if (_barcodeIndex.containsKey(gtin)) return _barcodeIndex[gtin];
      if (gtin.startsWith('0')) {
        final ean13 = gtin.substring(1);
        if (_barcodeIndex.containsKey(ean13)) return _barcodeIndex[ean13];
      }
    }

    // 3. Substring match against indexed barcodes
    for (final entry in _barcodeIndex.entries) {
      if (entry.key.length >= 8 && cleanDigits.contains(entry.key)) {
        return entry.value;
      }
    }

    // 4. If scanned code contains text / drug names (e.g. QR code or smart prescription)
    final words = clean.split(RegExp(r'[^a-zA-Z\u0621-\u064A0-9]+')).where((w) => w.length > 2);
    for (final word in words) {
      final searchResults = search(word);
      if (searchResults.isNotEmpty) {
        return searchResults.first;
      }
    }

    return null;
  }
